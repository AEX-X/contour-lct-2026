function makeTarget(
  type: WorkOrderTarget['type'],
  id: string,
  facilityId: string,
  displayName: string,
  hierarchyPath: WorkOrderTarget['hierarchyPath'],
): WorkOrderTarget {
  const facility = facilityRows.find((item) => item.id === facilityId)
  return {
    type,
    id,
    facilityId,
    displayName,
    hierarchyPath,
    locationSnapshot: {
      text: facility?.address ?? null,
      geo: facility?.position ?? null,
      planPosition: facilityId === 'fac-001' ? { planId: 'plan-fac-001', x: 62, y: 38, level: '-1' } : null,
    },
  }
}

